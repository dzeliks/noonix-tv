def main(path):
    tree = ET.parse(path)
    missing = []
    for ctx in tree.getroot().iter("context"):
        name = ctx.find("name").text
        for m in ctx.iter("message"):
            src = m.find("source").text
            tr = m.find("translation")
            if m.get("numerus") == "yes":
                forms = PLURALS.get(src)
                if not forms:
                    missing.append(f"{name}: {src}")
                    continue
                for f in list(tr):
                    tr.remove(f)
                for f in forms:
                    ET.SubElement(tr, "numerusform").text = f
            else:
                text = BY_CONTEXT.get((name, src), T.get(src))
                if text is None:
                    missing.append(f"{name}: {src}")
                    continue
                tr.text = text
            tr.attrib.pop("type", None)
    ET.indent(tree, space="    ")
    tree.write(path, encoding="utf-8", xml_declaration=True)
    with open(path, "r+", encoding="utf-8") as f:
        body = f.read().replace("<?xml version='1.0' encoding='utf-8'?>", '<?xml version="1.0" encoding="utf-8"?>\n<!DOCTYPE TS>', 1)
        f.seek(0)
        f.write(body)
        f.truncate()
    for m in missing:
        print("untranslated:", m)
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else "i18n/noonix-tv_sr_Latn.ts"))
